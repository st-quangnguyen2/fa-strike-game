const DICT: Record<Lang, Record<Key, string>> = { vi, en };
let lang: Lang = 'vi';

export function detectLang(): Lang {
  return (navigator.language || 'vi').toLowerCase().startsWith('vi') ? 'vi' : 'en';
}
export function getLang(): Lang { return lang; }
export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.desc'));
  document.getElementById('game')?.setAttribute('aria-label', t('meta.title'));
}
/** Lấy chuỗi theo ngôn ngữ hiện tại, thay {tên} bằng tham số. */
export function t(key: Key, p?: Record<string, string | number>): string {
  let s = DICT[lang][key];
  if (p) for (const [k, v] of Object.entries(p)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
/** Locale định dạng số: 12.400 (vi) hoặc 12,400 (en). */
export const numberLocale = () => (lang === 'vi' ? 'vi-VN' : 'en-US');
